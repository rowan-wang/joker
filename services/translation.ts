export function translateText(text: string): string {
    if (!text) return text;
    
    let translated = text;

    // 1. Replace specific phrases first (Longer matches first)
    // "+4 Mult" -> "+4 倍率"
    translated = translated.replace(/\+(\d+)\s*Mult/gi, "+$1 倍率");
    translated = translated.replace(/\+(\d+)\s*Chips/gi, "+$1 筹码");
    translated = translated.replace(/X(\d+(\.\d+)?)\s*Mult/gi, "X$1 倍率");
    translated = translated.replace(/1 in (\d+) chance/gi, "$1 分之一几率");
    translated = translated.replace(/Played cards with/gi, "打出的");
    translated = translated.replace(/Played cards/gi, "打出的牌");
    translated = translated.replace(/gives/gi, "给予");
    translated = translated.replace(/Create a/gi, "生成一张");
    translated = translated.replace(/Gains \+(\d+) Mult/gi, "获得 +$1 倍率");
    translated = translated.replace(/Gains \+(\d+) Chips/gi, "获得 +$1 筹码");
    translated = translated.replace(/Retrigger all played (.+)/gi, "再次触发所有打出的$1");
    translated = translated.replace(/if played hand contains a (.+)/gi, "如果打出的牌型包含$1");
    translated = translated.replace(/Each played (.+) gives/gi, "每张打出的$1给予");
    translated = translated.replace(/Every played (.+) permanently gains (.+)/gi, "每张打出的$1永久获得$2");
    translated = translated.replace(/when scored/gi, "计分时");
    translated = translated.replace(/Earns (\$\d+) at end of round/gi, "回合结束时获得$1");
    translated = translated.replace(/Gains (.+) if (.+)/gi, "如果$2，则获得$1");
    
    // 2. Replace dictionary words
    // We iterate through keys and replace word-boundary matches to avoid partial replacements
    // (e.g. avoiding replacing "Mult" inside "Multiple" if that existed, though less likely here)
    
    Object.entries(DICTIONARY).forEach(([key, value]) => {
        // Escape regex special characters in key
        const escapedKey = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const regex = new RegExp(`\\b${escapedKey}\\b`, 'gi');
        translated = translated.replace(regex, value);
    });

    return translated;
}
